/** The deck a first visit to the library offers to open: six slides on writing markdown. */
export const sampleDeck = `# How to write Markdown

Plain text with a few marks. Each slide in this deck shows one.

---

## Headings

Start a line with \`#\` for a title, \`##\` for a heading, \`###\` for a smaller one.

---

## Emphasis

Wrap words in \`*stars*\` for *italics* and \`**two stars**\` for **bold**.

---

## Lists

- Start a line with \`-\` for a bullet
- Or \`1.\` for a numbered list

---

## Links and code

Write a link as \`[text](https://example.com)\`. Wrap code in backticks: \`like this\`.

---

## New slides

A line with only \`---\`, with a blank line above it, starts a new slide.
`;
